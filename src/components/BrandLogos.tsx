export const BRAND_ASSETS: Record<string, string> = {
  apple: "/logos marcas/apple.svg",
  samsung: "/logos marcas/samsung.svg",
  xiaomi: "/logos marcas/xiaomi.svg",
  redmi: "/logos marcas/xiaomi.svg",
  poco: "/logos marcas/xiaomi.svg",
  motorola: "/logos marcas/motorola.svg",
  moto: "/logos marcas/motorola.svg",
  tecno: "/logos marcas/logotecno.svg",
  infinix: "/logos marcas/logoinifinix.jpg",
  honor: "/logos marcas/honor.svg",
};

export interface BrandLogoProps extends React.HTMLAttributes<HTMLElement> {
  brand: string;
  alt?: string;
  src?: string;
}

export const BrandLogo: React.FC<BrandLogoProps> = ({
  brand,
  alt,
  src,
  className,
  style,
  ...props
}) => {
  const [imgError, setImgError] = React.useState(false);
  const norm = (brand || "").toLowerCase().trim();
  const assetSrc = src || BRAND_ASSETS[norm];
  const defaultAlt = `Logo oficial ${brand}`;

  const renderFallbackSvg = () => {
    const svgProps = {
      className,
      style: { color: "currentColor", ...style },
      "aria-label": alt || defaultAlt,
      role: "img",
      ...props,
    };

    switch (norm) {
      case "apple":
        return <AppleLogo data-testid={props["data-testid"] || "brand-logo-apple"} {...svgProps} />;
      case "samsung":
        return <SamsungLogo data-testid={props["data-testid"] || "brand-logo-samsung"} {...svgProps} />;
      case "xiaomi":
      case "redmi":
      case "poco":
        return <XiaomiLogo data-testid={props["data-testid"] || "brand-logo-xiaomi"} {...svgProps} />;
      case "motorola":
      case "moto":
        return <MotorolaLogo data-testid={props["data-testid"] || "brand-logo-motorola"} {...svgProps} />;
      case "tecno":
        return <TecnoLogo data-testid={props["data-testid"] || "brand-logo-tecno"} {...svgProps} />;
      case "infinix":
        return <InfinixLogo data-testid={props["data-testid"] || "brand-logo-infinix"} {...svgProps} />;
      case "huawei":
        return <HuaweiLogo data-testid={props["data-testid"] || "brand-logo-huawei"} {...svgProps} />;
      case "honor":
        return <HonorLogo data-testid={props["data-testid"] || "brand-logo-honor"} {...svgProps} />;
      case "realme":
        return <RealmeLogo data-testid={props["data-testid"] || "brand-logo-realme"} {...svgProps} />;
      default:
        return null;
    }
  };

  if (assetSrc && !imgError) {
    return (
      <img
        src={assetSrc}
        alt={alt || defaultAlt}
        className={className}
        style={style}
        onError={() => setImgError(true)}
        loading="lazy"
        data-testid={props["data-testid"] || `brand-logo-img-${norm}`}
        {...(props as React.ImgHTMLAttributes<HTMLImageElement>)}
      />
    );
  }

  return renderFallbackSvg();
};
